#!/usr/bin/env python3
"""Start the WW Textile ERP as a shareable DEMO (fictional data only). Works on Windows, macOS and Linux.

  python deploy/run_demo.py            # public-demo mode: private passwords, secure cookies, login throttle, noindex
  python deploy/run_demo.py --local    # same data, relaxed for http://127.0.0.1 on your own computer
  python deploy/run_demo.py --reset    # delete the demo database and regenerate fresh fictional data, then start
  python deploy/run_demo.py --seed 5   # regenerate a different story (implies --reset)

On first run it creates .demo.env (mode 0600) holding a random secret key, a client password and a separate admin password.
Nothing in this file is committed or shown by the app. Put a tunnel or HTTPS reverse proxy in front for a public link (see DEMO.md).
"""
from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / ".demo.env"
WORDS = ["loom", "thread", "indigo", "cotton", "weave", "dye", "bobbin", "selvedge", "poplin", "twill", "lawn", "stitch", "cedar", "river", "amber"]


def load_or_create_env() -> dict[str, str]:
    vals: dict[str, str] = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, _, v = line.partition("=")
                vals[k.strip()] = v.strip()
    changed = False
    if len(vals.get("WW_SECRET_KEY", "")) < 32:
        vals["WW_SECRET_KEY"] = secrets.token_hex(32); changed = True
    if len(vals.get("WW_DEMO_PASSWORD", "")) < 10:
        vals["WW_DEMO_PASSWORD"] = "-".join(secrets.choice(WORDS) for _ in range(3)) + f"-{secrets.randbelow(9000) + 1000}"; changed = True
    if len(vals.get("WW_DEMO_ADMIN_PASSWORD", "")) < 12:
        vals["WW_DEMO_ADMIN_PASSWORD"] = secrets.token_urlsafe(16); changed = True
    if changed:
        ENV_FILE.write_text("# Generated by deploy/run_demo.py. Private: never commit or share this file.\n" + "".join(f"{k}={v}\n" for k, v in vals.items()))
        try:
            os.chmod(ENV_FILE, 0o600)
        except OSError:
            pass
    return vals


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--local", action="store_true", help="relaxed mode for http://127.0.0.1 (no Secure cookies, no public-demo checks)")
    ap.add_argument("--reset", action="store_true", help="delete the demo database and regenerate the fictional data first")
    ap.add_argument("--seed", type=int, help="random seed for the generated data (implies --reset)")
    ap.add_argument("--host", default="127.0.0.1", help="bind address (keep 127.0.0.1; expose it through a tunnel / proxy)")
    ap.add_argument("--port", type=int, default=8000)
    args = ap.parse_args()

    missing = []
    for mod, pkg in (("starlette", "starlette"), ("jinja2", "jinja2"), ("uvicorn", "uvicorn"), ("multipart", "python-multipart"), ("itsdangerous", "itsdangerous")):
        try:
            __import__(mod)
        except ImportError:
            missing.append(pkg)
    if missing:
        print(f"Missing packages: {', '.join(missing)}\nInstall them with:  {sys.executable} -m pip install -r requirements.txt", file=sys.stderr)
        return 2

    vals = load_or_create_env()
    env = {
        "WW_ENV": "demo", "WW_SECRET_KEY": vals["WW_SECRET_KEY"], "WW_DEMO_PASSWORD": vals["WW_DEMO_PASSWORD"],
        "WW_DEMO_ADMIN_PASSWORD": vals["WW_DEMO_ADMIN_PASSWORD"], "WW_PUBLIC_DEMO": "0" if args.local else "1",
        "WW_COOKIE_SECURE": "0" if args.local else "1", "WW_MAX_UPLOAD_MB": "3",
        "WW_DB_PATH": str(ROOT / "data" / "demo" / "wwtextile.db"), "WW_UPLOAD_DIR": str(ROOT / "data" / "demo" / "uploads"),
    }
    # Optional real AI / voice providers: read from .demo.env or the shell. Keys stay on the server and are never printed or sent to the browser.
    for src in (vals, os.environ):
        for k, v in src.items():
            if k.startswith(("WW_AI_", "WW_STT_", "WW_TTS_")) and v:
                env[k] = v
    for k, v in env.items():
        os.environ.setdefault(k, v) if k in ("WW_DB_PATH", "WW_UPLOAD_DIR", "WW_MAX_UPLOAD_MB") else os.environ.__setitem__(k, v)
    os.chdir(ROOT)
    sys.path.insert(0, str(ROOT))
    from wwtextile import cli

    if args.reset or args.seed is not None:
        rc = cli.main(["reset-demo", "--yes"] + (["--seed", str(args.seed)] if args.seed is not None else []))
        if rc:
            return rc
    print("\n" + "=" * 70)
    print("WW Textile ERP - DEMO (fictional data only)")
    print(f"  Client logins : ceo, manager1, manager2, store1, store2, prod1, prod2, gate1, gate2, fin1")
    print(f"  Client password (share this): {env['WW_DEMO_PASSWORD']}")
    print(f"  Admin login   : admin / {env['WW_DEMO_ADMIN_PASSWORD']}   (keep private - can reset the demo)")
    print(f"  Local address : http://{args.host}:{args.port}   health: /healthz")
    print("  Public link   : run a tunnel to that address in another terminal (DEMO.md)")
    ai_on = bool(env.get("WW_AI_PROVIDER") and env.get("WW_AI_API_KEY") and env.get("WW_AI_MODEL"))
    print("  AI model      : " + (f"CONNECTED ({env['WW_AI_PROVIDER']}, model {env['WW_AI_MODEL']}); max {env.get('WW_AI_MAX_PER_HOUR', '60')} AI answers per user per hour" if ai_on
                                   else "not connected - the built-in rule engine answers (add WW_AI_* to .demo.env, see DEMO.md)"))
    print("  Server voice  : " + ("speech-to-text connected" if env.get("WW_STT_API_KEY") else "no server speech-to-text (browser voice is used)")
          + ("; text-to-speech connected" if env.get("WW_TTS_API_KEY") else "; no server text-to-speech"))
    print("=" * 70 + "\n", flush=True)
    return cli.main(["demo", "--host", args.host, "--port", str(args.port)])


if __name__ == "__main__":
    sys.exit(main())
